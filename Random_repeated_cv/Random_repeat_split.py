from sklearn.model_selection import KFold



# CONFIGURATION
N_REPETITIONS = 10
N_OUTER_SPLITS = 5
N_INNER_SPLITS = 5
BASE_SEED = 1000
INNER_SEED_OFFSET = 10000
OUTPUT_SHUFFLE_OFFSET = 20000



# LOAD + CLEAN DATASET
def load_dataset(feature_file):
    if not os.path.isfile(feature_file):
        raise FileNotFoundError(
            f"\nDataset not found:\n{feature_file}"
        )

    # Original script used header=None.
    df = pd.read_csv(feature_file, header=None)

    if df.empty:
        raise ValueError("\nThe dataset is empty.")

    # The ID must be generated by this script.
    if "ID" in df.columns:
        raise ValueError(
            "\nThe input dataset already contains an 'ID' column.\n"
            "Please remove or rename the existing ID column."
        )

    original_rows = len(df)


    # Assign permanent IDs BEFORE cleaning.

    df.insert(
        0,
        "ID",
        [f"ID{i}" for i in range(1, original_rows + 1)]
    )

    print("\n" + "=" * 75)
    print("DATASET INFORMATION")
    print("=" * 75)

    print(f"\nInput dataset       : {feature_file}")
    print(f"Original rows       : {original_rows}")
    print("Permanent ID format : ID1, ID2, ID3, ...")


    # Clean feature + target columns only.

    data_columns = df.columns[1:]

    df[data_columns] = df[data_columns].replace(
        [np.inf, -np.inf],
        np.nan
    )

    df = df.dropna(
        subset=data_columns
    ).reset_index(drop=True)

    removed_rows = original_rows - len(df)

    print(f"Rows after cleaning : {len(df)}")
    print(f"Rows removed        : {removed_rows}")
    print(f"Number of columns   : {len(df.columns)}")


    # ID integrity checks.

    if df["ID"].duplicated().any():
        raise RuntimeError("\nDuplicate IDs detected.")

    if df["ID"].isna().any():
        raise RuntimeError("\nMissing IDs detected.")

    if len(df) < N_OUTER_SPLITS:
        raise ValueError(
            f"\nOnly {len(df)} valid rows remain. "
            f"{N_OUTER_SPLITS} outer folds are required."
        )

    print("ID integrity        : PASSED")

    return df



# OUTER SPLITS
def generate_outer_splits(df):

    split_records = []

    n_samples = len(df)
    row_to_id = dict(enumerate(df["ID"].values))

    for repetition in range(1, N_REPETITIONS + 1):

        rep_seed = BASE_SEED + repetition

        outer_kf = KFold(
            n_splits=N_OUTER_SPLITS,
            shuffle=True,
            random_state=rep_seed
        )

        print(
            f"\nOuter repetition {repetition}/{N_REPETITIONS}"
            f" | seed = {rep_seed}"
        )

        for fold, (train_idx, test_idx) in enumerate(
            outer_kf.split(np.arange(n_samples)),
            start=1
        ):

            train_idx = np.asarray(train_idx, dtype=int)
            test_idx = np.asarray(test_idx, dtype=int)

            # Validate before output-order shuffle.
            if set(train_idx).intersection(set(test_idx)):
                raise RuntimeError(
                    f"Outer train/test overlap detected in "
                    f"Repetition {repetition}, Fold {fold}."
                )

            if len(train_idx) + len(test_idx) != n_samples:
                raise RuntimeError(
                    f"Outer train + test != total samples in "
                    f"Repetition {repetition}, Fold {fold}."
                )

            shuffle_seed = (
                BASE_SEED
                + repetition * 100
                + fold
                + OUTPUT_SHUFFLE_OFFSET
            )

            rng = np.random.default_rng(shuffle_seed)
            rng.shuffle(train_idx)
            rng.shuffle(test_idx)

            for idx in train_idx:
                split_records.append({
                    "Repetition": repetition,
                    "Fold": fold,
                    "ID": row_to_id[int(idx)],
                    "Set": "train"
                })

            for idx in test_idx:
                split_records.append({
                    "Repetition": repetition,
                    "Fold": fold,
                    "ID": row_to_id[int(idx)],
                    "Set": "test"
                })

            train_percent = 100 * len(train_idx) / n_samples
            test_percent = 100 * len(test_idx) / n_samples

            print(
                f"  Fold {fold}/{N_OUTER_SPLITS}"
                f" | Train = {len(train_idx)} ({train_percent:.2f}%)"
                f" | Test = {len(test_idx)} ({test_percent:.2f}%)"
            )

    return pd.DataFrame(
        split_records,
        columns=["Repetition", "Fold", "ID", "Set"]
    )



# INNER SPLITS


def generate_inner_splits(df, outer_splits):
    inner_records = []

    id_to_position = {
        str(id_value): position
        for position, id_value in enumerate(df["ID"].values)
    }

    for repetition in range(1, N_REPETITIONS + 1):

        for outer_fold in range(1, N_OUTER_SPLITS + 1):

            current_outer = outer_splits[
                (outer_splits["Repetition"] == repetition)
                & (outer_splits["Fold"] == outer_fold)
            ]

            outer_train_ids = current_outer.loc[
                current_outer["Set"] == "train",
                "ID"
            ].astype(str).tolist()

            outer_test_ids = current_outer.loc[
                current_outer["Set"] == "test",
                "ID"
            ].astype(str).tolist()

            if not outer_train_ids or not outer_test_ids:
                raise RuntimeError(
                    f"Empty outer train/test set for "
                    f"Repetition={repetition}, Outer_Fold={outer_fold}."
                )

            # Safety: inner CV must be generated ONLY from outer train.
            if set(outer_train_ids).intersection(set(outer_test_ids)):
                raise RuntimeError(
                    f"Outer train/test overlap detected before inner CV "
                    f"for Repetition={repetition}, Outer_Fold={outer_fold}."
                )

            outer_train_positions = np.asarray(
                [id_to_position[id_value] for id_value in outer_train_ids],
                dtype=int
            )

            if len(outer_train_positions) < N_INNER_SPLITS:
                raise ValueError(
                    f"Not enough outer-training samples for "
                    f"{N_INNER_SPLITS} inner folds in "
                    f"Repetition={repetition}, Outer_Fold={outer_fold}."
                )

           
            inner_seed = (
                BASE_SEED
                + INNER_SEED_OFFSET
                + repetition * 100
                + outer_fold
            )

            inner_kf = KFold(
                n_splits=N_INNER_SPLITS,
                shuffle=True,
                random_state=inner_seed
            )

            print(
                f"\n  Inner CV | Repetition {repetition}"
                f" | Outer fold {outer_fold}"
                f" | seed = {inner_seed}"
            )

            for inner_fold, (
                inner_train_local,
                inner_val_local
            ) in enumerate(
                inner_kf.split(outer_train_positions),
                start=1
            ):

                inner_train_positions = outer_train_positions[
                    inner_train_local
                ]

                inner_val_positions = outer_train_positions[
                    inner_val_local
                ]

                inner_train_ids = [
                    str(df.iloc[position]["ID"])
                    for position in inner_train_positions
                ]

                inner_val_ids = [
                    str(df.iloc[position]["ID"])
                    for position in inner_val_positions
                ]


                # Critical leakage checks.

                if set(inner_train_ids).intersection(
                    set(inner_val_ids)
                ):
                    raise RuntimeError(
                        f"Inner train/validation overlap detected in "
                        f"Repetition={repetition}, "
                        f"Outer_Fold={outer_fold}, "
                        f"Inner_Fold={inner_fold}."
                    )

                if not set(inner_train_ids).issubset(
                    set(outer_train_ids)
                ):
                    raise RuntimeError(
                        f"Inner training contains an outer-test sample in "
                        f"Repetition={repetition}, "
                        f"Outer_Fold={outer_fold}, "
                        f"Inner_Fold={inner_fold}."
                    )

                if not set(inner_val_ids).issubset(
                    set(outer_train_ids)
                ):
                    raise RuntimeError(
                        f"Inner validation contains an outer-test sample in "
                        f"Repetition={repetition}, "
                        f"Outer_Fold={outer_fold}, "
                        f"Inner_Fold={inner_fold}."
                    )

                # Deterministic output ordering.
                output_seed = (
                    BASE_SEED
                    + OUTPUT_SHUFFLE_OFFSET
                    + repetition * 1000
                    + outer_fold * 100
                    + inner_fold
                )

                rng = np.random.default_rng(output_seed)

                inner_train_ids = np.asarray(
                    inner_train_ids,
                    dtype=object
                )
                inner_val_ids = np.asarray(
                    inner_val_ids,
                    dtype=object
                )

                rng.shuffle(inner_train_ids)
                rng.shuffle(inner_val_ids)

                for id_value in inner_train_ids:
                    inner_records.append({
                        "Repetition": repetition,
                        "Outer_Fold": outer_fold,
                        "Inner_Fold": inner_fold,
                        "ID": str(id_value),
                        "Set": "train"
                    })

                for id_value in inner_val_ids:
                    inner_records.append({
                        "Repetition": repetition,
                        "Outer_Fold": outer_fold,
                        "Inner_Fold": inner_fold,
                        "ID": str(id_value),
                        "Set": "validation"
                    })

                print(
                    f"    Inner fold {inner_fold}/{N_INNER_SPLITS}"
                    f" | Train = {len(inner_train_ids)}"
                    f" | Validation = {len(inner_val_ids)}"
                )

    return pd.DataFrame(
        inner_records,
        columns=[
            "Repetition",
            "Outer_Fold",
            "Inner_Fold",
            "ID",
            "Set"
        ]
    )



# VALIDATE OUTER SPLITS


def validate_outer_splits(splits_df, df):
    """Thorough validation of all 50 outer assignments."""

    print("\n" + "=" * 75)
    print("VALIDATING OUTER SPLITS")
    print("=" * 75)

    expected_ids = set(df["ID"].astype(str))

    combinations = (
        splits_df[["Repetition", "Fold"]]
        .drop_duplicates()
    )

    expected_combinations = N_REPETITIONS * N_OUTER_SPLITS

    if len(combinations) != expected_combinations:
        raise RuntimeError(
            f"Expected {expected_combinations} outer combinations, "
            f"found {len(combinations)}."
        )

    for repetition in range(1, N_REPETITIONS + 1):
        for fold in range(1, N_OUTER_SPLITS + 1):

            current = splits_df[
                (splits_df["Repetition"] == repetition)
                & (splits_df["Fold"] == fold)
            ]

            train = current[current["Set"] == "train"]
            test = current[current["Set"] == "test"]

            train_ids = set(train["ID"].astype(str))
            test_ids = set(test["ID"].astype(str))

            if train["ID"].duplicated().any():
                raise RuntimeError(
                    f"Duplicate outer train ID in "
                    f"Repetition={repetition}, Fold={fold}."
                )

            if test["ID"].duplicated().any():
                raise RuntimeError(
                    f"Duplicate outer test ID in "
                    f"Repetition={repetition}, Fold={fold}."
                )

            if train_ids.intersection(test_ids):
                raise RuntimeError(
                    f"Outer train/test overlap in "
                    f"Repetition={repetition}, Fold={fold}."
                )

            if train_ids.union(test_ids) != expected_ids:
                raise RuntimeError(
                    f"Not all dataset IDs represented in "
                    f"Repetition={repetition}, Fold={fold}."
                )

    if not set(splits_df["Set"]).issubset({"train", "test"}):
        raise RuntimeError("Invalid value in outer Set column.")

    print(" 50 outer repetition/fold combinations")
    print(" No duplicate IDs")
    print(" No train/test overlap")
    print(" Every sample represented in every outer fold")
    print(" All dataset IDs accounted for")
    print(" Outer split validation PASSED")



# VALIDATE INNER SPLITS


def validate_inner_splits(inner_df, outer_df, df):
    """Thorough validation of all 250 inner folds."""

    print("\n" + "=" * 75)
    print("VALIDATING INNER SPLITS")
    print("=" * 75)

    expected_ids = set(df["ID"].astype(str))

    expected_outer_combinations = (
        N_REPETITIONS * N_OUTER_SPLITS
    )

    outer_combinations = (
        inner_df[["Repetition", "Outer_Fold"]]
        .drop_duplicates()
    )

    if len(outer_combinations) != expected_outer_combinations:
        raise RuntimeError(
            f"Expected {expected_outer_combinations} outer combinations "
            f"in inner split file, found {len(outer_combinations)}."
        )

    expected_inner_combinations = (
        N_REPETITIONS
        * N_OUTER_SPLITS
        * N_INNER_SPLITS
    )

    inner_combinations = (
        inner_df[
            ["Repetition", "Outer_Fold", "Inner_Fold"]
        ]
        .drop_duplicates()
    )

    if len(inner_combinations) != expected_inner_combinations:
        raise RuntimeError(
            f"Expected {expected_inner_combinations} inner folds, "
            f"found {len(inner_combinations)}."
        )

    if not set(inner_df["Set"]).issubset(
        {"train", "validation"}
    ):
        raise RuntimeError(
            "Invalid value in inner Set column."
        )

    for repetition in range(1, N_REPETITIONS + 1):
        for outer_fold in range(1, N_OUTER_SPLITS + 1):

            current_outer = outer_df[
                (outer_df["Repetition"] == repetition)
                & (outer_df["Fold"] == outer_fold)
            ]

            outer_train_ids = set(
                current_outer.loc[
                    current_outer["Set"] == "train",
                    "ID"
                ].astype(str)
            )

            outer_test_ids = set(
                current_outer.loc[
                    current_outer["Set"] == "test",
                    "ID"
                ].astype(str)
            )

            if not outer_train_ids:
                raise RuntimeError(
                    f"Empty outer training set for "
                    f"Repetition={repetition}, Outer_Fold={outer_fold}."
                )

            for inner_fold in range(1, N_INNER_SPLITS + 1):

                current_inner = inner_df[
                    (inner_df["Repetition"] == repetition)
                    & (inner_df["Outer_Fold"] == outer_fold)
                    & (inner_df["Inner_Fold"] == inner_fold)
                ]

                inner_train_ids = set(
                    current_inner.loc[
                        current_inner["Set"] == "train",
                        "ID"
                    ].astype(str)
                )

                inner_val_ids = set(
                    current_inner.loc[
                        current_inner["Set"] == "validation",
                        "ID"
                    ].astype(str)
                )

                if not inner_train_ids:
                    raise RuntimeError(
                        f"Empty inner train set for "
                        f"Repetition={repetition}, "
                        f"Outer_Fold={outer_fold}, "
                        f"Inner_Fold={inner_fold}."
                    )

                if not inner_val_ids:
                    raise RuntimeError(
                        f"Empty inner validation set for "
                        f"Repetition={repetition}, "
                        f"Outer_Fold={outer_fold}, "
                        f"Inner_Fold={inner_fold}."
                    )

                if inner_train_ids.intersection(
                    inner_val_ids
                ):
                    raise RuntimeError(
                        f"Inner train/validation overlap for "
                        f"Repetition={repetition}, "
                        f"Outer_Fold={outer_fold}, "
                        f"Inner_Fold={inner_fold}."
                    )

                # Most important nested-CV check:
                # inner samples must be a subset of outer train.
                if not inner_train_ids.issubset(
                    outer_train_ids
                ):
                    raise RuntimeError(
                        f"Inner training contains outer-test samples for "
                        f"Repetition={repetition}, "
                        f"Outer_Fold={outer_fold}, "
                        f"Inner_Fold={inner_fold}."
                    )

                if not inner_val_ids.issubset(
                    outer_train_ids
                ):
                    raise RuntimeError(
                        f"Inner validation contains outer-test samples for "
                        f"Repetition={repetition}, "
                        f"Outer_Fold={outer_fold}, "
                        f"Inner_Fold={inner_fold}."
                    )

                # No unexpected IDs.
                if not (
                    inner_train_ids | inner_val_ids
                ).issubset(expected_ids):
                    raise RuntimeError(
                        f"Unknown dataset ID in inner split for "
                        f"Repetition={repetition}, "
                        f"Outer_Fold={outer_fold}, "
                        f"Inner_Fold={inner_fold}."
                    )

                # Inner train + validation should exactly equal
                # the complete outer-training set.
                if (
                    inner_train_ids | inner_val_ids
                ) != outer_train_ids:
                    raise RuntimeError(
                        f"Inner train + validation does not equal the "
                        f"outer-training set for "
                        f"Repetition={repetition}, "
                        f"Outer_Fold={outer_fold}, "
                        f"Inner_Fold={inner_fold}."
                    )

                # Explicitly verify no outer-test ID appears.
                if (
                    inner_train_ids | inner_val_ids
                ).intersection(outer_test_ids):
                    raise RuntimeError(
                        f"Outer-test leakage detected for "
                        f"Repetition={repetition}, "
                        f"Outer_Fold={outer_fold}, "
                        f"Inner_Fold={inner_fold}."
                    )

    print(" 250 inner folds")
    print(" Every inner fold has train + validation")
    print(" No inner train/validation overlap")
    print(" Inner data always comes only from outer training")
    print(" No outer-test samples inside inner CV")
    print(" Inner train + validation = complete outer training set")
    print(" All inner split validation PASSED")



# SUMMARIES


def create_outer_summary(splits_df):
    records = []

    for repetition in range(1, N_REPETITIONS + 1):
        for fold in range(1, N_OUTER_SPLITS + 1):

            current = splits_df[
                (splits_df["Repetition"] == repetition)
                & (splits_df["Fold"] == fold)
            ]

            train_n = (
                current["Set"] == "train"
            ).sum()

            test_n = (
                current["Set"] == "test"
            ).sum()

            total_n = train_n + test_n

            records.append({
                "Repetition": repetition,
                "Outer_Fold": fold,
                "Train_N": train_n,
                "Test_N": test_n,
                "Total_N": total_n,
                "Train_Percent": 100 * train_n / total_n,
                "Test_Percent": 100 * test_n / total_n,
            })

    return pd.DataFrame(records)


def create_inner_summary(inner_df):
    records = []

    for repetition in range(1, N_REPETITIONS + 1):
        for outer_fold in range(1, N_OUTER_SPLITS + 1):
            for inner_fold in range(1, N_INNER_SPLITS + 1):

                current = inner_df[
                    (inner_df["Repetition"] == repetition)
                    & (inner_df["Outer_Fold"] == outer_fold)
                    & (inner_df["Inner_Fold"] == inner_fold)
                ]

                train_n = (
                    current["Set"] == "train"
                ).sum()

                validation_n = (
                    current["Set"] == "validation"
                ).sum()

                total_n = train_n + validation_n

                records.append({
                    "Repetition": repetition,
                    "Outer_Fold": outer_fold,
                    "Inner_Fold": inner_fold,
                    "Train_N": train_n,
                    "Validation_N": validation_n,
                    "Total_N": total_n,
                    "Train_Percent": (
                        100 * train_n / total_n
                    ),
                    "Validation_Percent": (
                        100 * validation_n / total_n
                    ),
                })

    return pd.DataFrame(records)



